export default function SocialAuthButtons({
  onGoogleClick,
  onGithubClick,
  onDiscordClick,
  className = '',
}) {
  const handleGoogle = (e) => {
    e.preventDefault();
    if (onGoogleClick) onGoogleClick();
    else alert('Đang kết nối Google OAuth...');
  };

  const handleGithub = (e) => {
    e.preventDefault();
    if (onGithubClick) onGithubClick();
    else alert('Đang kết nối GitHub OAuth...');
  };

  const handleDiscord = (e) => {
    e.preventDefault();
    if (onDiscordClick) onDiscordClick();
    else alert('Đang kết nối Discord OAuth...');
  };

  return (
    <div className={`uiverse-social-wrap ${className}`.trim()}>
      {/* 1. Google Button */}
      <button
        type="button"
        className="uiverse-btn uiverse-btn-google group"
        title="Đăng nhập bằng Google"
        onClick={handleGoogle}
      >
        <div className="uiverse-shimmer" />
        <div className="uiverse-icon-wrap">
          <GoogleIcon />
        </div>
      </button>

      {/* 2. GitHub Button */}
      <button
        type="button"
        className="uiverse-btn uiverse-btn-github group"
        title="Đăng nhập bằng GitHub"
        onClick={handleGithub}
      >
        <div className="uiverse-shimmer" />
        <div className="uiverse-icon-wrap text-white">
          <GithubIcon />
        </div>
      </button>

      {/* 3. Discord Button */}
      <button
        type="button"
        className="uiverse-btn uiverse-btn-discord group"
        title="Đăng nhập bằng Discord"
        onClick={handleDiscord}
      >
        <div className="uiverse-shimmer" />
        <div className="uiverse-icon-wrap text-[#5865F2]">
          <DiscordIcon />
        </div>
      </button>
    </div>
  );
}
